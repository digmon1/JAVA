class BitwiseOP{
		public static void main(String... args){
		
		System.out.println(5&6);
		System.out.println(5|6);
		System.out.println(5^6);
		System.out.println(10<<3);
		System.out.println(-10<<2);
		System.out.println(52>>2);
		System.out.println(-48>>2);
		System.out.println(-52>>>3);
		System.out.println(~573);
	}

}
/*
	bitwise operator
		1.& -and
		2.| (or)
		3.^ (X-or)
		4.<< (left shift)
		5.>> (signed right shift)
		6.>>> (unsigned right shift)
		7.~ (Negation/Complement)
	
*/